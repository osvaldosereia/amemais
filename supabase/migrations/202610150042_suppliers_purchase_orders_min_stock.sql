CREATE TABLE public.suppliers(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 name text NOT NULL CHECK(length(trim(name)) BETWEEN 2 AND 150),
 contact_name text,
 phone text,
 email text,
 document text,
 notes text,
 active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX suppliers_unique_active_name ON public.suppliers(lower(trim(name))) WHERE active;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS min_stock integer NOT NULL DEFAULT 0
 CONSTRAINT products_min_stock_range CHECK(min_stock BETWEEN 0 AND 1000000);
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS supplier_id uuid REFERENCES public.suppliers(id) ON DELETE SET NULL;
CREATE INDEX products_supplier_idx ON public.products(supplier_id);
CREATE INDEX products_min_stock_idx ON public.products(min_stock) WHERE active AND min_stock>0;

CREATE TABLE public.purchase_orders(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
 supplier_id uuid NOT NULL REFERENCES public.suppliers(id),
 status text NOT NULL DEFAULT 'rascunho'
  CHECK(status IN ('rascunho','enviado','finalizado','cancelado')),
 note text,
 created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 sent_at timestamptz,
 finished_at timestamptz
);
CREATE INDEX purchase_orders_supplier_idx ON public.purchase_orders(supplier_id,created_at DESC);
CREATE TABLE public.purchase_order_items(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 purchase_order_id uuid NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
 product_id uuid NOT NULL REFERENCES public.products(id),
 product_name text NOT NULL,
 sku text,
 ean text,
 quantity integer NOT NULL CHECK(quantity BETWEEN 1 AND 1000000),
 UNIQUE(purchase_order_id,product_id)
);
CREATE INDEX purchase_order_items_product_idx ON public.purchase_order_items(product_id);

