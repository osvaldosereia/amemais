CREATE OR REPLACE FUNCTION public.save_purchase_order(
 p_supplier uuid,p_items jsonb,p_note text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_order uuid; r record; v_count integer; v_rows integer:=0;
BEGIN
 IF auth.uid() IS NULL OR NOT app_private.has_permission('purchases.manage') THEN
  RAISE EXCEPTION 'Sem autorização para compras'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.suppliers WHERE id=p_supplier AND active)
 THEN RAISE EXCEPTION 'Fornecedor inválido ou inativo'; END IF;
 IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
 OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 300
 THEN RAISE EXCEPTION 'Inclua de 1 a 300 produtos no pedido';END IF;
 SELECT count(*),count(distinct (x->>'product_id')) INTO v_count,v_rows
 FROM jsonb_array_elements(p_items) x;
 IF v_count<>v_rows THEN RAISE EXCEPTION 'Produto repetido no pedido';END IF;
 IF length(coalesce(p_note,''))>1500 THEN RAISE EXCEPTION 'Observação muito longa';END IF;
 INSERT INTO public.purchase_orders(supplier_id,note,created_by)
 VALUES(p_supplier,nullif(trim(p_note),''),auth.uid()) RETURNING id INTO v_order;
 FOR r IN SELECT product_id,quantity FROM jsonb_to_recordset(p_items)
 AS x(product_id uuid,quantity integer) LOOP
  IF r.quantity IS NULL OR r.quantity NOT BETWEEN 1 AND 1000000
   THEN RAISE EXCEPTION 'Quantidade de compra inválida'; END IF;
  INSERT INTO public.purchase_order_items(purchase_order_id,product_id,product_name,sku,ean,quantity)
  SELECT v_order,p.id,p.name,p.sku,p.ean,r.quantity
  FROM public.products p WHERE p.id=r.product_id AND p.active AND p.supplier_id=p_supplier;
  IF NOT FOUND THEN RAISE EXCEPTION 'Produto indisponível ou de outro fornecedor'; END IF;
 END LOOP;
 INSERT INTO public.audit_log(entity,entity_id,action,actor_id,details)
 VALUES('purchase_orders',v_order::text,'PURCHASE_ORDER_CREATED',auth.uid(),
  jsonb_build_object('supplier_id',p_supplier,'items',v_count));
 RETURN v_order;
END;$fn$;
REVOKE ALL ON FUNCTION public.save_purchase_order(uuid,jsonb,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.save_purchase_order(uuid,jsonb,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.set_purchase_order_status(p_id uuid,p_status text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_order public.purchase_orders%rowtype;
BEGIN
 IF auth.uid() IS NULL OR NOT app_private.has_permission('purchases.manage') THEN
  RAISE EXCEPTION 'Sem autorização para compras';END IF;
 SELECT * INTO v_order FROM public.purchase_orders WHERE id=p_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Pedido de compra não localizado'; END IF;
 IF NOT (
   (v_order.status='rascunho' AND p_status IN ('enviado','cancelado')) OR
   (v_order.status='enviado' AND p_status IN ('finalizado','cancelado'))
 ) THEN RAISE EXCEPTION 'Transição de status inválida'; END IF;
 UPDATE public.purchase_orders SET status=p_status,updated_at=now(),
  sent_at=CASE WHEN p_status='enviado' THEN now() ELSE sent_at END,
  finished_at=CASE WHEN p_status='finalizado' THEN now() ELSE finished_at END
 WHERE id=p_id;
 INSERT INTO public.audit_log(entity,entity_id,action,actor_id,details)
 VALUES('purchase_orders',p_id::text,'PURCHASE_STATUS_CHANGED',auth.uid(),
  jsonb_build_object('before',v_order.status,'after',p_status,
  'stock_updated',false));
END;$fn$;
REVOKE ALL ON FUNCTION public.set_purchase_order_status(uuid,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.set_purchase_order_status(uuid,text) TO authenticated;

-- Integra cadastro de roupas por modelo, aplicando o mínimo igualmente a cada SKU.
CREATE OR REPLACE FUNCTION public.set_apparel_procurement(p_model uuid,p_supplier uuid,p_min_stock integer)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
BEGIN
 IF auth.uid() IS NULL OR NOT app_private.has_permission('products.edit') THEN
  RAISE EXCEPTION 'Sem permissão de edição de produtos'; END IF;
 IF p_min_stock IS NULL OR p_min_stock NOT BETWEEN 0 AND 1000000
 THEN RAISE EXCEPTION 'Estoque mínimo inválido'; END IF;
 IF p_supplier IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.suppliers WHERE id=p_supplier AND active)
 THEN RAISE EXCEPTION 'Fornecedor não disponível'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.apparel_models WHERE id=p_model)
 THEN RAISE EXCEPTION 'Modelo não encontrado'; END IF;
 UPDATE public.products SET supplier_id=p_supplier,min_stock=p_min_stock
 WHERE apparel_model_id=p_model;
 INSERT INTO public.audit_log(entity,entity_id,action,actor_id,details)
 VALUES('apparel_models',p_model::text,'PROCUREMENT_UPDATED',auth.uid(),
  jsonb_build_object('supplier_id',p_supplier,'min_per_sku',p_min_stock));
END;$fn$;
REVOKE ALL ON FUNCTION public.set_apparel_procurement(uuid,uuid,integer) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.set_apparel_procurement(uuid,uuid,integer) TO authenticated;
